def data_stats():
    import svalbardradar.interpretations

    data = svalbardradar.interpretations.merge_all_interpretations()

    antenna_alias = {"25 MHz": "low", "100 MHz": "high"}
    per_antenna_stats = {}
    for antenna, a_data in data.groupby("antenna"):
        if antenna not in antenna_alias:
            continue

        e_user = a_data["thickness_user_nmad"].median()
        wavelength = 168 / int(antenna.split(" ")[0])
        per_antenna_stats[antenna_alias[antenna]] = {
            "median": e_user,
            "perwavelength": int(round(100 * e_user / wavelength)),
        }

    svalbardradar.analysis.record_information(
        {
            "perantenna": {
                "e_user": per_antenna_stats,
            }
        }
    )

    cts_relevant = (data["temperate_frac"] > 0.1) & (data["temperate_frac"] < 0.9)

    high_bad_concensus_frac = np.count_nonzero(data["thickness_user_nmad"] > 20) / data.shape[0]
    record_information(
        {
            "data": {
                "bad_consensus_frac": int(round(high_bad_concensus_frac * 1000)),
                "uncertainty": {
                    "bed": data["thickness_nmad"].median(),
                    "bed_pm": stats.nmad(data["thickness_nmad"]),
                    "cts": data.loc[cts_relevant, "temperate_nmad"].median(),
                    "cts_pm": stats.nmad(data.loc[cts_relevant, "temperate_nmad"]),
                    "e_gpr": data["thickness_gpr_uncertainty"].median(),
                    "e_gpr_pm": stats.nmad(data["thickness_gpr_uncertainty"]),
                    "e_gnss": data["thickness_gnss_uncertainty"].median(),
                    "e_gnss_pm": stats.nmad(data["thickness_gnss_uncertainty"]),
                    "e_user": data["thickness_user_nmad"].median(),
                    "e_user_pm": stats.nmad(data["thickness_user_nmad"]),
                },
            },
            "temperate_fractions": {
                "average": round(100 * (data["temperate_frac"] * data["thickness"]).sum() / data["thickness"].sum())

            }
        }
    )


