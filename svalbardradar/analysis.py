def format_float(number: float, decimals: int = 1) -> str:
    """

    Examples
    --------
    >>> format_float(1.3456)
    '1.35'
    >>> format_float(1.3)
    '1.30'
    """
    rounded = str(round(float(number), decimals))

    if "." not in rounded:
        rounded += "." + "0" * decimals
    elif (n_zeros := len(rounded.split(".")[-1])) != decimals:
        rounded += "0" * (decimals - n_zeros)

    return rounded


def rec_update_dict(dictionary: dict, new: dict, i: int = 0, max_i: int = 20):
    if i == max_i:
        raise RecursionError("Max recursion limit reached")

    for key, value in new.items():
        if isinstance(value, collections.abc.Mapping):
            dictionary[key] = rec_update_dict(
                dictionary.get(key, {}),
                value,
                i=i + 1,
                max_i=max_i,  # pyright: ignore[reportArgumentType]
            )
        else:
            dictionary[key] = value
    return dictionary


def rec_to_tex_macros(
    dictionary: dict | collections.abc.Mapping, pre_key: str = "", i: int = 0, max_i: int = 20
) -> list[str]:
    if i == max_i:
        raise RecursionError("Max recursion limit reached")

    macros = []

    if i == 0:
        macros.append("% Autogenerated macro file.\n")
    for key, value in dictionary.items():
        new_key = ".".join([pre_key, key]) if len(pre_key) > 0 else key
        if isinstance(value, collections.abc.Mapping):
            macros += rec_to_tex_macros(value, pre_key=new_key, i=i + 1, max_i=max_i)
        else:
            macros += [
                f"% {new_key}",
                "\\def\\dataX" + new_key.replace(".", "X").replace("_", "") + "/{" + str(value) + "}",
            ]

    return macros


def format_values(obj: object, i: int = 0, max_i: int = 20) -> object:
    if isinstance(obj, str):
        return obj
    if hasattr(obj, "dtype"):
        obj = obj.item()
    if isinstance(obj, float):
        formatted = format_float(obj)
        return formatted
    if isinstance(obj, collections.abc.Mapping):
        new_obj = {}
        for key, value in obj.items():
            new_obj[key] = format_values(value, i=i + 1, max_i=max_i)
        return new_obj
    elif isinstance(obj, collections.abc.Sequence):
        new_obj = []
        for value in obj:
            new_obj.append(format_values(value, i=i + 1, max_i=max_i))

    return obj


def record_information(new_info: dict[str, object] | None = None) -> dict[str, object]:
    info_path = Path("tables/statistics.json")
    info_tex_path = info_path.with_suffix(".tex")

    if info_path.is_file():
        with open(info_path) as infile:
            info = json.load(infile)
    else:
        info = {}

    if new_info is not None:
        info = rec_update_dict(info, new_info)

        info_path.parent.mkdir(exist_ok=True, parents=True)
        with open(info_path, "w") as outfile:
            json.dump(
                format_values(info),
                outfile,
                indent=2,
            )
        with open(info_path) as infile:
            info = json.load(infile)

        info_tex = rec_to_tex_macros(info)
        with open(info_tex_path, "w") as outfile:
            outfile.write("\n".join(info_tex))

    return info


def glacier_table():
    import svalbardradar.interpretations
    import svalbardradar.figures

    data = svalbardradar.interpretations.merge_all_interpretations()

    data["glacier"] = data["radar_key"].str.split("-", expand=True).iloc[:, 0]

    distances = data.groupby(["glacier", "radar_key"])["distance"].max().groupby("glacier").sum()

    outlines = svalbardradar.figures.get_svalbard_glaciers()
    glaciers = gpd.read_file("shapes/glacier_locations.geojson")

    glaciers = gpd.sjoin(glaciers, outlines, how="left", predicate="intersects")
    glaciers["geometry"] = outlines.loc[glaciers["index_right"].values, "geometry"].values

    glaciers["track_length"] = distances.loc[glaciers["key"]].values / 1e3

    record_information({"total_profile_length_km": int(round(glaciers["track_length"].sum()))})
    glaciers["track_length"] = glaciers["track_length"].round().astype(int)
    glaciers["area"] = (glaciers["Shape_Area"] * 1e-6).round().astype(int)

    glaciers["zrange"] = (
        glaciers["minZ"].round().astype(int).astype(str) + "–" + glaciers["maxZ"].round().astype(int).astype(str)
    )

    cols = {
        "name": "Glacier",
        "area": "Area (km²)",
        "zrange": "Elevation range (m a.s.l.)",
        "track_length": "GPR profile length (km)",
        "last_surge": "Last surge",
    }

    no_date = "No date$^{[2]}$"
    surging = {
        "etonbreen": "2023$^{[1]}$",
        "von_postbreen": "1870$^{[2]}$",
        "elfenbeinbreen": "1903$^{[2]}$",
        "jinnbreen": no_date,
        "moysalbreen": "1925$^{[2]}$",
        "lofthusbreen": "1896$^{[3]}$",
        "dronbreen": "1896$^{[3]}$",
        "scott_turnerbreen": "1914$^{[3]}$",
        "bergmesterbreen": no_date,
        "rugaasfonna": no_date,
        "svellnosbreen": no_date,
        "kroppbreen": "2000s$^{[4]}$",
        "edvardbreen": "$\\sim$2025$^{[1]}$",
        "vallakrabreen": "2022$^{[1]}$",
        "mettebreen": no_date,
        "ragna_mariebreen": no_date,
        "filantropbreen": no_date,
        "antoniabreen": no_date,
        "finsterwalderbreen": "1914$^{[2]}$",
    }
    glaciers["last_surge"] = glaciers["key"].map(lambda k: surging.get(k, "-"))

    tex_table = r"\begin{tabular}{l" + "c" * (len(cols) - 1) + "}\n"
    tex_table += "&".join((r"\textbf{" + v + "}" for v in cols.values())) + "\\\\\n\\midrule\n"

    for _, glacier in glaciers.sort_values("Y_cent", ascending=False).iterrows():
        tex_table += "&".join((str(glacier[col]) for col in cols))
        tex_table += "\\\\\n"

    tex_table += r"\end{tabular}"

    out_path = Path("tables/glacier_table.tex")
    out_path.parent.mkdir(exist_ok=True, parents=True)
    out_path.write_text(tex_table)
    print(tex_table)


